-- ============================================================================
-- V4 — Modulos, paginas y permisos: la plataforma deja de ser una sola app
-- ============================================================================
--
-- Hasta hoy la navegacion de la aplicacion es un array escrito a mano en
-- AppNavigator.tsx: quien entra ve las dos aplicaciones —finanzas y ayuno—
-- siempre, porque asi esta puesto en el fichero. Meter una tercera significaba
-- editar ese array y volver a publicar.
--
-- Aqui una aplicacion pasa a ser una fila con sus paginas, y quien la ve lo
-- decide un permiso por rol.
--
-- TRES DECISIONES QUE SE VEN EN ESTE FICHERO
--
--  1. NO EXISTIR ES NO PODER. Si no hay fila en oc_auth_role_permission para
--     (rol, pagina), ese rol no tiene nada ahi. La alternativa —una fila con
--     los cuatro permisos en falso— obliga a mantener al dia el producto de
--     roles por paginas, y el dia que se anade una pagina y falta la fila el
--     sistema tendria que decidir solo.
--
--  2. LAS PAGINAS QUE SE SIEMBRAN SON LAS QUE EXISTEN HOY, con el nombre de
--     ruta EXACTO que usa el navegador del movil. Una fila cuyo "route" no
--     corresponda con ninguna pantalla es un boton que no lleva a ningun
--     sitio; hay una prueba que compara ambas listas.
--
--  3. EL MODULO DE ADMINISTRACION NACE VACIO DE USUARIOS. Solo ADMIN tiene
--     permiso sobre el, y ADMIN lo llevan las cuentas que la V3 marco.
--
-- Sintaxis valida tal cual en PostgreSQL y en H2.
-- ============================================================================

CREATE TABLE oc_auth_module (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY,
    code       VARCHAR(50)  NOT NULL UNIQUE,
    name       VARCHAR(100) NOT NULL,
    icon       VARCHAR(50),
    sort_order INTEGER      NOT NULL,
    active     BOOLEAN      NOT NULL,
    created_at TIMESTAMP(6),
    updated_at TIMESTAMP(6),
    PRIMARY KEY (id)
);

CREATE TABLE oc_auth_page (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY,
    module_id  BIGINT       NOT NULL,
    code       VARCHAR(50)  NOT NULL,
    name       VARCHAR(100) NOT NULL,
    route      VARCHAR(100) NOT NULL,
    icon       VARCHAR(50),
    in_menu    BOOLEAN      NOT NULL,
    sort_order INTEGER      NOT NULL,
    active     BOOLEAN      NOT NULL,
    created_at TIMESTAMP(6),
    updated_at TIMESTAMP(6),
    PRIMARY KEY (id),
    CONSTRAINT fk_pagina_modulo FOREIGN KEY (module_id) REFERENCES oc_auth_module (id),
    CONSTRAINT uk_pagina_modulo_codigo UNIQUE (module_id, code)
);

CREATE TABLE oc_auth_role_permission (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY,
    role_id    BIGINT  NOT NULL,
    page_id    BIGINT  NOT NULL,
    can_read   BOOLEAN NOT NULL,
    can_create BOOLEAN NOT NULL,
    can_update BOOLEAN NOT NULL,
    can_delete BOOLEAN NOT NULL,
    active     BOOLEAN NOT NULL,
    created_at TIMESTAMP(6),
    updated_at TIMESTAMP(6),
    PRIMARY KEY (id),
    CONSTRAINT fk_permiso_rol FOREIGN KEY (role_id)
        REFERENCES oc_auth_role (id) ON DELETE CASCADE,
    CONSTRAINT fk_permiso_pagina FOREIGN KEY (page_id)
        REFERENCES oc_auth_page (id) ON DELETE CASCADE,
    CONSTRAINT uk_permiso_rol_pagina UNIQUE (role_id, page_id)
);

CREATE INDEX idx_permiso_rol ON oc_auth_role_permission (role_id);

