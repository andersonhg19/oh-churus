-- ---------------------------------------------------------------------------
-- Permisos
--
-- USER hace vida normal en finanzas y ayuno. ADMIN lo mismo, y ademas
-- administracion. Nadie mas tiene nada, porque no hay fila.
-- ---------------------------------------------------------------------------

INSERT INTO oc_auth_role_permission (role_id, page_id, can_read, can_create, can_update, can_delete, active, created_at, updated_at)
SELECT r.id, pg.id, TRUE, TRUE, TRUE, TRUE, TRUE, CURRENT_TIMESTAMP, CURRENT_TIMESTAMP
FROM oc_auth_role r
CROSS JOIN oc_auth_page pg
JOIN oc_auth_module m ON m.id = pg.module_id
WHERE r.name IN ('USER', 'ADMIN')
  AND m.code IN ('finanzas', 'ayuno');

