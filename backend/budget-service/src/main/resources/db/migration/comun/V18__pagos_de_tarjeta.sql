-- Ola 7.2: pagar la tarjeta con el monto que se quiera (mayor que cero y
-- hasta lo que se debe a la fecha del pago), no solo "todo hasta el corte".
--
-- El pago salda las compras mas viejas primero. Lo que sobra y no alcanza a
-- cubrir la siguiente compra completa queda como ABONO en la tarjeta (credit)
-- y se descuenta de lo que se debe. Cada pago queda anotado aqui.
ALTER TABLE oc_budget_card ADD COLUMN IF NOT EXISTS credit NUMERIC(15,2) NOT NULL DEFAULT 0;

CREATE TABLE IF NOT EXISTS oc_budget_card_payment (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY,
    card_id      BIGINT        NOT NULL,
    user_id      BIGINT        NOT NULL,
    amount       NUMERIC(15,2) NOT NULL,
    payment_date DATE          NOT NULL,
    created_at   TIMESTAMP(6),
    PRIMARY KEY (id)
);
CREATE INDEX IF NOT EXISTS idx_card_payment_card ON oc_budget_card_payment (card_id, payment_date);
