-- Punto 3 del backlog, abierto desde la fase 1 de marzo: la moneda y los
-- decimales eran globales y vivian en el formateador del movil, con "es-CO",
-- el simbolo "$" y cero decimales escritos a mano. Cambiarlo obligaba a tocar
-- codigo y volver a publicar.
--
-- DOS NIVELES, Y ESE ES EL DISENO
--
--  1. oc_auth_app_config: lo que vale para toda la instalacion mientras nadie
--     diga lo contrario. Es una tabla clave-valor a proposito: lo que se
--     guarda aqui son ajustes que se consultan de uno en uno y cambian una vez
--     al ano, no datos con estructura.
--
--  2. Las columnas nuevas de oc_auth_user: lo que esa persona prefiere. Nulo
--     significa "lo que diga la configuracion global", no "sin moneda". Por
--     eso NO llevan valor por defecto ni NOT NULL: un defecto en la columna
--     congelaria la eleccion global del dia en que se creo la cuenta.
--
-- El plazo de decimales se limita en la base y no solo en el DTO: un 12 ahi
-- rompe el formateador del movil, y ese fallo llegaria como una pantalla en
-- blanco sin explicacion.
-- ============================================================================

ALTER TABLE oc_auth_user ADD COLUMN currency VARCHAR(10);
ALTER TABLE oc_auth_user ADD COLUMN decimal_places INTEGER;

ALTER TABLE oc_auth_user
    ADD CONSTRAINT ck_usuario_decimales CHECK (decimal_places IS NULL OR decimal_places BETWEEN 0 AND 4);

CREATE TABLE oc_auth_app_config (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY,
    config_key  VARCHAR(80)  NOT NULL UNIQUE,
    config_value VARCHAR(300) NOT NULL,
    description VARCHAR(300),
    active      BOOLEAN      NOT NULL,
    created_at  TIMESTAMP(6),
    updated_at  TIMESTAMP(6),
    PRIMARY KEY (id)
);

