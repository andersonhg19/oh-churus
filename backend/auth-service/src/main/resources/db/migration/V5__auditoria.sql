-- ============================================================================
-- V5 — Auditoria: quien cambio que, cuando, y de que a que
-- ============================================================================
--
-- Con roles en juego la pregunta deja de ser academica. Si una cuenta amanece
-- con ADMIN hay que poder decir quien se lo dio y a que hora, y hasta esta
-- migracion la unica respuesta posible era mirar los logs de la aplicacion —si
-- es que seguian ahi.
--
-- DOS COSAS QUE ESTA TABLA HACE Y NO SE VEN A SIMPLE VISTA
--
--  1. GUARDA EL CORREO DEL ACTOR ADEMAS DE SU ID. Es duplicar un dato a
--     proposito. Si esa cuenta se borra manana, la linea tiene que seguir
--     diciendo algo; un registro historico describe el mundo como era
--     entonces, no como es ahora. Por lo mismo no hay clave ajena hacia la
--     tabla de usuarios: borrar una cuenta no puede llevarse por delante el
--     rastro de lo que hizo.
--
--  2. LOS INDICES ESTAN DESDE EL PRIMER DIA. Una tabla de auditoria solo
--     crece, y cuando se nota que va lenta ya tiene demasiadas filas como para
--     indexarla en caliente sin bloquear el servicio de autenticacion.
--
-- El borrado por antiguedad lo hace RetencionDeAuditoria, configurable con
-- audit.retention-days y con un pase nocturno.
-- ============================================================================

CREATE TABLE oc_auth_audit_log (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY,
    actor_user_id BIGINT,
    actor_email   VARCHAR(150),
    entity_type   VARCHAR(60)  NOT NULL,
    entity_id     BIGINT,
    action        VARCHAR(40)  NOT NULL,
    details       VARCHAR(1000),
    occurred_at   TIMESTAMP(6) NOT NULL,
    PRIMARY KEY (id)
);

CREATE INDEX idx_auditoria_actor ON oc_auth_audit_log (actor_user_id);
CREATE INDEX idx_auditoria_entidad ON oc_auth_audit_log (entity_type, entity_id);
CREATE INDEX idx_auditoria_fecha ON oc_auth_audit_log (occurred_at);
