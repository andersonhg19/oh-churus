-- Ola 7: tarjetas de credito y compras a cuotas.
--
-- Una tarjeta es de quien la usa (user_id) y la ve su hogar (household_id),
-- para que en Deudas se vea lo que debe cada uno. No guarda saldo: lo que se
-- debe se calcula con las compras hechas con ella que aun no se pagan.
CREATE TABLE IF NOT EXISTS oc_budget_card (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY,
    user_id      BIGINT       NOT NULL,
    household_id BIGINT,
    name         VARCHAR(60)  NOT NULL,
    color        VARCHAR(7),
    payment_day  INTEGER,
    active       BOOLEAN      NOT NULL,
    created_at   TIMESTAMP(6),
    updated_at   TIMESTAMP(6),
    PRIMARY KEY (id)
);
CREATE INDEX IF NOT EXISTS idx_card_user_active ON oc_budget_card (user_id, active);

-- La compra con tarjeta es un gasto normal de su categoria (cuenta el mes en
-- que se hace; a varias cuotas, cada cuota cuenta en su mes). Estas columnas
-- dicen con que tarjeta, que cuota es y si la tarjeta ya se pago.
ALTER TABLE oc_budget_movement ADD COLUMN IF NOT EXISTS card_id BIGINT;
ALTER TABLE oc_budget_movement ADD COLUMN IF NOT EXISTS card_paid BOOLEAN NOT NULL DEFAULT FALSE;
ALTER TABLE oc_budget_movement ADD COLUMN IF NOT EXISTS installment_number INTEGER;
ALTER TABLE oc_budget_movement ADD COLUMN IF NOT EXISTS installment_total INTEGER;
-- Las cuotas de una misma compra comparten purchase_id (el id de la primera).
ALTER TABLE oc_budget_movement ADD COLUMN IF NOT EXISTS purchase_id BIGINT;
CREATE INDEX IF NOT EXISTS idx_movement_card ON oc_budget_movement (card_id, card_paid, active);
