-- V3 — Roles: la segunda pregunta
-- ============================================================================
--
-- La ola 2 dejo resuelto QUIEN eres: el userId sale del token y ningun
-- endpoint vuelve a aceptarlo por el cuerpo. Lo que nunca se respondio es QUE
-- PUEDES HACER. Hasta este fichero, la unica regla de autorizacion de los tres
-- servicios era anyRequest().authenticated(), y eso significa que el usuario
-- demo podia pedir /v1/users/all y leerse los correos de todo el mundo.
--
-- DOS DETALLES DE ESTE FICHERO QUE SON DECISIONES, NO ADORNOS
--
--  1. LA CASCADA VA EN UN SOLO SENTIDO. Al borrar un usuario se van sus
--     asignaciones (ON DELETE CASCADE en user_id), porque son suyas y de nadie
--     mas. Al intentar borrar un ROL asignado, la clave ajena lo impide: los
--     roles son compartidos. En los dos proyectos que sirvieron de referencia
--     esto esta puesto como CascadeType.ALL de usuario a roles, que es lo
--     contrario: borrar un usuario intenta borrar los roles de todos.
--
--  2. EL RELLENO NO DEJA A NADIE FUERA. Toda cuenta existente recibe USER en
--     la misma migracion. Si esto no estuviera, al desplegar la version que
--     exige rol nadie podria entrar a nada, incluido quien despliega.
--
-- Sintaxis valida tal cual en PostgreSQL y en H2, como el resto de las
-- migraciones de este servicio.
-- ============================================================================

CREATE TABLE oc_auth_role (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY,
    name        VARCHAR(50)  NOT NULL UNIQUE,
    description VARCHAR(200),
    active      BOOLEAN      NOT NULL,
    created_at  TIMESTAMP(6),
    updated_at  TIMESTAMP(6),
    PRIMARY KEY (id)
);

ALTER TABLE oc_auth_role
    ADD CONSTRAINT ck_rol_nombre_no_vacio CHECK (CHAR_LENGTH(TRIM(name)) > 0);

CREATE TABLE oc_auth_user_role (
    user_id BIGINT NOT NULL,
    role_id BIGINT NOT NULL,
    PRIMARY KEY (user_id, role_id),
    CONSTRAINT fk_user_role_user FOREIGN KEY (user_id)
        REFERENCES oc_auth_user (id) ON DELETE CASCADE,
    CONSTRAINT fk_user_role_role FOREIGN KEY (role_id)
        REFERENCES oc_auth_role (id)
);

CREATE INDEX idx_user_role_role ON oc_auth_user_role (role_id);

-- Los dos roles con los que arranca la plataforma. ADMIN administra usuarios,
-- roles y modulos; USER usa la aplicacion. Cualquier rol adicional se crea
-- desde la pantalla de administracion, no desde aqui.
INSERT INTO oc_auth_role (name, description, active, created_at, updated_at)
VALUES ('ADMIN', 'Administra usuarios, roles y modulos de la plataforma', TRUE,
        CURRENT_TIMESTAMP, CURRENT_TIMESTAMP);

INSERT INTO oc_auth_role (name, description, active, created_at, updated_at)
VALUES ('USER', 'Usa la aplicacion con sus propios datos', TRUE,
        CURRENT_TIMESTAMP, CURRENT_TIMESTAMP);

-- Relleno: todo el mundo es USER.
INSERT INTO oc_auth_user_role (user_id, role_id)
SELECT u.id, r.id
FROM oc_auth_user u
CROSS JOIN oc_auth_role r
WHERE r.name = 'USER';

-- Y ademas ADMIN quien administra. Si estos correos no existen en la base, el
-- INSERT no inserta nada y la migracion sigue: es un SELECT, no un UPDATE a
-- ciegas. Para una instalacion con otros correos, el primer ADMIN se asigna
-- desde la semilla (LoadData) o a mano.
INSERT INTO oc_auth_user_role (user_id, role_id)
SELECT u.id, r.id
FROM oc_auth_user u
CROSS JOIN oc_auth_role r
WHERE r.name = 'ADMIN'
  AND u.email IN ('admin@ohchurus.com', 'anderson@ohchurus.com');
